#!/usr/bin/env python3
"""Generate src/fxp_fft_tables.c: const Q15 twiddles and bit-reversal for the fixed-point FFT.
W512[k] = exp(-j*2*pi*k/512), k = 0..383, rounded to nearest Q15 and clamped to [-32767, 32767]
(never -32768, so products stay inside int32 bounds). The radix-4 256-pt complex FFT needs W512 up to
index 3*(q-1)*128/q < 384; the real split uses k <= 128. digrev256 is the base-4 digit reversal.
cos512_q14[m] = cos(2*pi*m/512) in Q14 (|v| <= 16384), m = 0..511, for the sparse real DFT (fxp_rdft.c);
sin is read as cos[(m - 128) & 511].
tw256 holds the radix-4 stage twiddles in reading order (copies of W512 entries)."""
import math, pathlib
q = lambda v: max(-32767, min(32767, int(math.floor(v * 32768 + 0.5))))
rows = []
for k in range(384):
    a = -2 * math.pi * k / 512
    rows.append(f'{{{q(math.cos(a))}, {q(math.sin(a))}}}')
def d4(i):
    r = 0
    for _ in range(4):
        r = r * 4 + (i & 3); i >>= 2
    return r
br = [d4(i) for i in range(256)]
out = ['/* Generated by tools/gen/gen-fft-tables.py — do not edit. */', '#include "fxp_fft.h"', '',
       '/* W512[k] = exp(-j 2 pi k / 512), Q15, k = 0..383 */',
       'const cq15_t fxp_w512[384] = {']
out += ['\t' + ', '.join(rows[i:i + 4]) + ',' for i in range(0, 384, 4)]
out += ['};', '', '/* base-4 digit reversal for the radix-4 256-pt complex FFT */', 'const uint8_t fxp_digrev256[256] = {']
out += ['\t' + ', '.join(map(str, br[i:i + 16])) + ',' for i in range(0, 256, 16)]
tw = []
for qq in (4, 16, 64):  # per-stage twiddles, in the order fxp_cfft256 reads them: j = 1..q-1, then w1, w2, w3
    st = 128 // qq
    for j in range(1, qq):
        tw += [rows[j * st], rows[2 * j * st], rows[3 * j * st]]
out += ['};', '', '/* radix-4 stage twiddles, copies of fxp_w512: q = 4 at 0, q = 16 at 9, q = 64 at 54;',
        ' * entry 3 (j - 1) + m - 1 = W512^(m j 128 / q), m = 1..3 */', f'const cq15_t fxp_tw256[{len(tw)}] = {{']
out += ['\t' + ', '.join(tw[i:i + 4]) + ',' for i in range(0, len(tw), 4)]
q14 = lambda v: int(math.floor(v * 16384 + 0.5))
cs = [q14(math.cos(2 * math.pi * m / 512)) for m in range(512)]
out += ['};', '', '/* cos(2 pi m / 512), Q14, m = 0..511 (sparse real DFT twiddles) */', 'const int16_t fxp_cos512_q14[512] = {']
out += ['\t' + ', '.join(map(str, cs[i:i + 16])) + ',' for i in range(0, 512, 16)]
out += ['};', '']
p = pathlib.Path(__file__).resolve().parents[2] / 'src/fxp_fft_tables.c'
p.write_text('\n'.join(out))
print('wrote', p)
