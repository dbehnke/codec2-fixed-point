#!/usr/bin/env python3
"""Generate src/fxp_math_tables.c (const tables for fxp_math.c / fxp_lpcspec.c).
fxp_cosq_q30[j] = cos(pi*j/1024) in Q30, j = 0..512 (quarter wave; full circle by symmetry, 2048 steps).
fxp_log2_q16[j] = log2(1 + j/128) in Q16, j = 0..128 (linear interpolation in fxp_log2_q16()).
fxp_exp2_q30[j] = 2^(j/128) in Q30 as uint32, j = 0..128 (2^31 at j = 128).
fxp_atan_tab_u32[j] = atan(j/256) in turns * 2^32 (uint32 angle), j = 0..256 (2^29 at j = 256)."""
import math, pathlib
r = lambda v: int(math.floor(v + 0.5))
cq = [r(math.cos(math.pi * j / 1024) * 2**30) for j in range(513)]
lg = [r(math.log2(1 + j / 128) * 65536) for j in range(129)]
ex = [r(2 ** (j / 128) * 2**30) for j in range(129)]
at = [r(math.atan(j / 256) / (2 * math.pi) * 2**32) for j in range(257)]
def rows(v, n, fmt=str):
    return ['\t' + ', '.join(fmt(x) for x in v[i:i + n]) + ',' for i in range(0, len(v), n)]
out = ['/* Generated by tools/gen/gen-math-tables.py — do not edit. */', '#include "fxp_math.h"', '',
       '/* cos(pi j / 1024), Q30, j = 0..512 */', 'const int32_t fxp_cosq_q30[513] = {']
out += rows(cq, 8) + ['};', '', '/* log2(1 + j/128), Q16, j = 0..128 */', 'const int32_t fxp_log2_tab_q16[129] = {']
out += rows(lg, 12) + ['};', '', '/* 2^(j/128), Q30, j = 0..128 */', 'const uint32_t fxp_exp2_tab_q30[129] = {']
out += rows(ex, 8, lambda x: f'{x}u') + ['};', '', '/* atan(j/256) / 2pi * 2^32, j = 0..256 */', 'const uint32_t fxp_atan_tab_u32[257] = {']
out += rows(at, 8, lambda x: f'{x}u') + ['};', '']
p = pathlib.Path(__file__).resolve().parents[2] / 'src/fxp_math_tables.c'
p.write_text('\n'.join(out)); print('wrote', p)
