#!/usr/bin/env python3
"""Generate src/fxp_lpc_tables.c (constants of the fixed-point LPC/LSP analysis, lpc.c).
fxp_bw_gamma_q30[i]   = round(2^30 g_i): the float encoder's 15 Hz bandwidth expansion (float32 values of its table)
fxp_acos_poly_q29[k]  = round(2^29 c_k): fast_acosf polynomial, highest power first (float32 values)
fxp_lpc_log2_wscale_q16 = round(2^16 log2(scale^2)), scale = 1 / sqrt(512 m), m = sum of the float Hann^2: the
                        float encoder's window normalisation, carried into log2 E
fxp_lpc_floor_r0      = ceil(1e-6 2^30 512 m): the float LPC_ENERGY_FLOOR (sum (Sn w)^2 < 1e-6) as a bound on the
                        integer R[0] = sum x^2 of the Q15-windowed speech at shift 0
fxp_lpc_hz_q29        = round(2^29 4000 / pi / 2^13): radians in Q29 to Hz in Q16 via (y K) >> 29
fxp_lpc_eidx_q29      = round(2^29 0.64 10 log10(2)): the energy quantiser slope in index units per log2 unit
"""
import math, pathlib, struct
f32 = lambda v: struct.unpack('f', struct.pack('f', v))[0]
r = lambda v: int(math.floor(v + 0.5))
NW, FFT = 279, 512
gamma = [1.0, 0.994, 0.988036, 0.982107784, 0.976215137296, 0.970357846472224, 0.964535699393391,
         0.95874848519703, 0.952995994285848, 0.947278018320133, 0.941594350210212]
acos_c = [-0.004731162409361028, 0.02013917916990988, -0.04547268716508862, 0.08798969877894365,
          -0.2145148619010314, 1.57079461300486]
# float window energy as the float encoder accumulates it (float32 Hann values, summed in float32)
m = 0.0
for j in range(NW):
    v = f32(0.5 - 0.5 * math.cos(f32(f32(2 * math.pi) * j / (NW - 1))))
    m = f32(m + f32(v * v))
gq = [r(f32(g) * 2**30) for g in gamma]
aq = [r(f32(c) * 2**29) for c in acos_c]
assert all(abs(v) < 2**31 for v in gq + aq)
lw = r(-math.log2(512 * m) * 65536)
floor_r0 = math.ceil(1e-6 * 2**30 * 512 * m)
hz = r(4000 / math.pi / 2**13 * 2**29)
eidx = r(0.64 * 10 * math.log10(2) * 2**29)
out = ['/* Generated by tools/gen/gen-lpc-tables.py — do not edit. */', '#include "lpc.h"', '',
       '/* 15 Hz bandwidth expansion g^i, Q30 */',
       'const int32_t fxp_bw_gamma_q30[LPC_ORD + 1] = {', '\t' + ', '.join(map(str, gq)) + ',', '};', '',
       '/* fast_acosf polynomial (highest power first), Q29 */',
       'const int32_t fxp_acos_poly_q29[6] = {', '\t' + ', '.join(map(str, aq)) + ',', '};', '',
       f'const int32_t fxp_lpc_log2_wscale_q16 = {lw}; /* log2(1 / (512 m)), m = {m!r} */',
       f'const uint32_t fxp_lpc_floor_r0 = {floor_r0};',
       f'const int32_t fxp_lpc_hz_q29 = {hz};',
       f'const int32_t fxp_lpc_eidx_q29 = {eidx};', '']
p = pathlib.Path(__file__).resolve().parents[2] / 'src/fxp_lpc_tables.c'
p.write_text('\n'.join(out))
print('wrote', p, 'm', m, 'floor', floor_r0)
