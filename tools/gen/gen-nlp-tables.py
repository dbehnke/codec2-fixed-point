#!/usr/bin/env python3
"""Generate src/fxp_nlp_tables.c (const tables for the fixed-point NLP pitch estimator, nlp.c).
fxp_nlp_fir_q15[k]  = round(2^15 h[k]), k = 0..47: the 48-tap decimation low-pass of the float NLP in time order,
                      acc = sum_k h[k] sq[n - k]. The float code stored it as a 5-phase polyphase bank,
                      poly[p][t] = h[p + 5 t] (two trailing zero entries pad it to 5 x 10).
fxp_nlp_hann_q15[i] = round(2^15 (0.5 - 0.5 cos(2 pi i / 63))), i = 0..63 (the float NLP window)."""
import math, pathlib
r = lambda v: int(math.floor(v + 0.5))
poly = [  # float polyphase bank of src/nlp.c (E1), phases 0..4, 10 taps each
    [-0.00108181240, 0.00200298490, 0.00080284511, -0.02092061000, 0.08630594400,
     0.13674206000, 0.00322047750, -0.01170581000, 0.00514494150, -0.00092768838],
    [-0.00110083440, 0.00370585090, -0.00482046100, -0.01280883100, 0.11480192000,
     0.11480192000, -0.01280883100, -0.00482046100, 0.00370585090, -0.00110083440],
    [-0.00092768838, 0.00514494150, -0.01170581000, 0.00322047750, 0.13674206000,
     0.08630594400, -0.02092061000, 0.00080284511, 0.00200298490, -0.00108181240],
    [-0.00042289438, 0.00559246660, -0.01819927500, 0.02668381100, 0.14867556000,
     0.05552062400, -0.02206528200, 0.00430367540, 0.00055034190, 0.0],
    [0.00055034190, 0.00430367540, -0.02206528200, 0.05552062400, 0.14867556000,
     0.02668381100, -0.01819927500, 0.00559246660, -0.00042289438, 0.0],
]
h = [0.0] * 50
for p in range(5):
    for t in range(10):
        h[p + 5 * t] = poly[p][t]
assert h[48] == 0.0 and h[49] == 0.0
h = h[:48]
assert all(abs(h[k] - h[47 - k]) < 1e-12 for k in range(48)), 'linear phase'
hq = [r(v * 2**15) for v in h]
w = [r((0.5 - 0.5 * math.cos(2 * math.pi * i / 63)) * 2**15) for i in range(64)]
assert max(w) < 32768
def rows(v, n):
    return ['\t' + ', '.join(str(x) for x in v[i:i + n]) + ',' for i in range(0, len(v), n)]
out = ['/* Generated by tools/gen/gen-nlp-tables.py — do not edit. */', '#include "nlp.h"', '',
       '/* NLP decimation low-pass, Q15, time order (acc = sum_k h[k] sq[n - k]) */',
       'const int16_t fxp_nlp_fir_q15[NLP_NTAP] = {']
out += rows(hq, 12) + ['};', '', '/* NLP window 0.5 - 0.5 cos(2 pi i / 63), Q15 */', 'const int16_t fxp_nlp_hann_q15[NDEC] = {']
out += rows(w, 12) + ['};', '']
# packed DFT twiddles: low half cos(2 pi m / 512), high half sin(2 pi m / 512), both Q14 and equal to
# fxp_cos512_q14[m] and fxp_cos512_q14[(m + 384) & 511] (same formula as tools/gen/gen-fft-tables.py)
q14 = lambda v: int(math.floor(v * 16384 + 0.5))
cs = [q14(math.cos(2 * math.pi * m / 512)) for m in range(512)]
pk = [(cs[m] & 0xffff) | ((cs[(m + 384) & 511] & 0xffff) << 16) for m in range(512)]
out += ['/* NLP DFT twiddles, packed: cos (Q14) in bits 0..15, sin (Q14) in bits 16..31; m = 0..511 */',
        'const uint32_t fxp_nlp_cs512[512] = {']
out += ['\t' + ', '.join(f'0x{v:08x}u' for v in pk[i:i + 8]) + ',' for i in range(0, 512, 8)]
out += ['};', '']
p = pathlib.Path(__file__).resolve().parents[2] / 'src/fxp_nlp_tables.c'
p.write_text('\n'.join(out))
print('wrote', p, 'sum h', sum(h), 'sum hq', sum(hq), 'sum|hq|', sum(abs(x) for x in hq))
