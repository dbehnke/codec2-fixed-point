#!/usr/bin/env python3
"""Generate src/fxp_analysis_tables.c (const tables for the fixed-point encoder analysis, analysis.c).
fxp_hann_q15[j]    = round(2^15 (0.5 - 0.5 cos(2 pi j / (NW - 1)))), j = 0..NW-1 (NW = 279; peak 2^15 at j = 139),
                     as uint16. The float encoder's window is this Hann times scale = 1 / sqrt(512 sum h^2).
fxp_winspec_q15[d] = W(d) / W(0) * 32767, d = 0..256: the real DFT (512 points) of the Hann centred at n = 0,
                     W(d) = sum_n h(139 + n) cos(2 pi d n / 512). Only ratios of W matter (voicing fit).
FXP_ANA_FLOOR_Q24  = 1e-4 * 512 * sum h^2 in Q24: the float voicing sums' 1e-4 floor expressed in units of the
                     unscaled-window spectrum power (see analysis.c)."""
import math, pathlib
NW = 279
r = lambda v: int(math.floor(v + 0.5))
h = [0.5 - 0.5 * math.cos(2 * math.pi * j / (NW - 1)) for j in range(NW)]
hq = [r(v * 2**15) for v in h]
W = [sum(h[139 + n] * math.cos(2 * math.pi * d * n / 512) for n in range(-139, 140)) for d in range(257)]
wq = [r(v / W[0] * 32767) for v in W]
floor_q24 = r(1e-4 * 512 * sum(v * v for v in h) * 2**24)
def rows(v, n):
    return ['\t' + ', '.join(str(x) for x in v[i:i + n]) + ',' for i in range(0, len(v), n)]
out = ['/* Generated by tools/gen/gen-analysis-tables.py — do not edit. */', '#include "analysis.h"', '',
       f'/* Hann window, Q15 (peak 32768), j = 0..{NW - 1} */', f'const uint16_t fxp_hann_q15[{NW}] = {{']
out += rows(hq, 12) + ['};', '', '/* window spectrum W(d) / W(0) * 32767, d = 0..256 */', 'const int16_t fxp_winspec_q15[257] = {']
out += rows(wq, 12) + ['};', '', f'const uint32_t fxp_ana_floor_q24 = {floor_q24}u; /* 1e-4 * 512 * sum h^2, Q24 */', '']
p = pathlib.Path(__file__).resolve().parents[2] / 'src/fxp_analysis_tables.c'
p.write_text('\n'.join(out)); print('wrote', p, 'floor', floor_q24 / 2**24, 'W tail', wq[20:30])
